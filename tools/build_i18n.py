# Builds i18n.js from tools/i18n_src.py. Run from the repo root: python3 tools/build_i18n.py
import json, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from i18n_src import T, P
data = {"T": {k: list(v) for k, v in T.items()}, "P": [list(p) for p in P]}
runtime = open(os.path.join(os.path.dirname(__file__), "i18n_runtime.js")).read()
open("i18n.js", "w").write("// Generated by tools/build_i18n.py: edit tools/i18n_src.py, not this file.\nwindow.I18N_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n" + runtime)
print(len(T), "phrases,", len(P), "patterns")
